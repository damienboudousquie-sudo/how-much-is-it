const LangContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void; t: Copy }>({
  lang: "en",
  setLang: () => undefined,
  t: en,
});

/** The language the visitor picked, or else the first browser language the site speaks. */
function readLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (isLang(saved)) return saved;
  } catch {
    // Storage can be blocked; fall back to the browser language.
  }
  return browserLang();
}

export function browserLang(): Lang {
  const wanted = typeof navigator === "undefined" ? [] : navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const tag of wanted) {
    const base = (tag ?? "").toLowerCase().split(/[-_]/)[0];
    if (isLang(base)) return base;
  }
  return "en";
}

let active: Lang | null = null;

export function currentLang(): Lang {
  return active ?? readLang();
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang);
  active = lang;
  setNumberLocale(lang);
  const value = useMemo(() => {
    // Only a language the visitor picks is remembered; otherwise the browser language keeps applying.
    const setLang = (next: Lang) => {
      try {
        localStorage.setItem(LANG_KEY, next);
      } catch {
        // Not saved; the choice still applies to this visit.
      }
      setLangState(next);
    };
    return { lang, setLang, t: tables[lang] };
  }, [lang]);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useI18n() {
  return useContext(LangContext);
}

export function copyFor(lang: Lang): Copy {
  return tables[lang];
}

export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}
